/**
 * 규칙을 사용자 말로 (UI-S3-010 · 개편안 4-5).
 *
 * 검수 결과 카드 머리와 리포트 판정 내역에 **규칙 번호 대신 이 이름**을 쓴다. 번호(R01…)는
 * 근거 보기 안으로 들어간다 — 실무자가 받는 문서에 `R04` 가 찍히면 내부 코드로 읽힌다.
 *
 * 화면과 리포트가 **한 자리**를 본다. 종전에는 이 표가 `apps/web` 에만 있어 PDF 가 번호를
 * 그대로 적었다 (#473).
 */
export const RULE_NAMES: Readonly<Record<string, string>> = {
  R01: '쉬는 날 · 운영시간',
  R02: '행사 기간',
  R03: '일정 시간 겹침',
  R04: '종류 쏠림',
  R05: '확정되지 않은 곳',
  R06: '정보 바뀜',
  R07: '식사 · 휴식',
  R08: '이동 시간',
  R09: '날씨 · 우천',
  R10: '상품 구성',
};

/** 모르는 코드는 그대로 돌려준다 — 이름이 없다고 판정을 숨기지 않는다 */
export function ruleName(code: string): string {
  return RULE_NAMES[code] ?? code;
}
